const siteRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const readerRoot = resolve(siteRoot, "..");
const markdownPunctuation = /[!"#$%&'()*+,\-./:;<=>?@[\\\]^_`{|}~]/g;

function plainText(value) {
  return String(value ?? "")
    .replace(/[\u0000-\u001f\u007f]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function escapeMarkdown(value) {
  return plainText(value).replace(markdownPunctuation, (character) => `\\${character}`);
}

function safeHttpUrl(value) {
  const candidate = plainText(value);
  if (!candidate) return "";
  try {
    const parsed = new URL(candidate);
    if (!["http:", "https:"].includes(parsed.protocol) || parsed.username || parsed.password) {
      return "";
    }
    return candidate.replaceAll("<", "%3C").replaceAll(">", "%3E");
  } catch {
    return "";
  }
}

function publicDigest(snapshot, limit = 100) {
  const articles = Array.isArray(snapshot.articles)
    ? snapshot.articles.filter((article) => article && typeof article === "object")
    : [];
  const selected = articles.slice(0, limit);
  const lines = [
    "# Aaron Reader Public Digest",
    "",
    "Generated by a fixed program; LLM tokens: 0.",
    "",
  ];
  if (selected.length === 0) {
    lines.push("There are no public articles.");
    return `${lines.join("\n")}\n`;
  }
  lines.push(
    `Showing the latest ${selected.length} of ${articles.length} public articles (limit: ${limit}).`,
    "",
  );
  for (const article of selected) {
    const title = escapeMarkdown(article.title || "Untitled");
    const url = safeHttpUrl(article.url);
    const titleMarkup = url ? `[${title}](<${url}>)` : title;
    const sourceName = escapeMarkdown(article.source_name || "Unknown source");
    const date = escapeMarkdown(plainText(article.published_at).slice(0, 10));
    lines.push(`- ${titleMarkup} — ${sourceName} · ${date}`);
  }
  return `${lines.join("\n")}\n`;
}

