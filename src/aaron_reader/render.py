def render_json(
    articles: Sequence[Dict[str, object]],
    statuses: Sequence[Dict[str, object]],
    *,
    counts: Optional[Dict[str, int]] = None,
    article_limit: Optional[int] = None,
    language: str = "en",
) -> str:
    resolved_language = _normalize_language(language)
    resolved_counts = _resolve_counts(articles, statuses, counts)
    returned_count = len(articles)
    result_limit = max(
        0,
        int(article_limit if article_limit is not None else returned_count),
    )
    omitted_count = max(0, resolved_counts["total"] - returned_count)
    cached_ai_artifact_count = sum(
        len(_translation_ai_artifacts(article.get("ai_artifacts")))
        for article in articles
    )
    payload = {
        "generated_at": datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z"),
        "language": resolved_language,
        "supported_languages": list(SUPPORTED_LANGUAGES),
        "llm_tokens_used": 0,
        "render_llm_tokens_used": 0,
        "cached_ai_artifact_count": cached_ai_artifact_count,
        "counts": resolved_counts,
        "articles_page": {
            "order": "newest_first",
            "returned_count": returned_count,
            "limit": result_limit,
            "omitted_count": omitted_count,
            "truncated": omitted_count > 0,
        },
        "sources": [
            {
                "slug": _output_text(source["slug"]),
                "name": _output_text(source["name"]),
                "health": _source_health(source),
                "last_success_at": _output_text(source.get("last_success_at")) or None,
                "last_error": _output_text(source.get("last_error")) or None,
                "article_count": int(source.get("article_count") or 0),
                "unread_count": int(source.get("unread_count") or 0),
                "pending_count": int(source.get("pending_count") or 0),
            }
            for source in statuses
        ],
        "articles": [_public_article(article) for article in articles],
    }
    return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"


def render_digest(
    articles: Sequence[Dict[str, object]],
    *,
    total_count: Optional[int] = None,
    article_limit: Optional[int] = None,
    language: str = "en",
) -> str:
    resolved_language = _normalize_language(language)
    translations = _TRANSLATIONS[resolved_language]
    resolved_total = max(len(articles), int(total_count or 0))
    resolved_limit = max(
        0,
        int(article_limit if article_limit is not None else len(articles)),
    )
    lines = [
        "# %s" % translations["digest_title"],
        "",
        translations["program_generated"],
        "",
    ]
    if not articles:
        lines.append(translations["digest_empty"])
        return "\n".join(lines) + "\n"
    lines.extend(
        [
            _format_translation(
                resolved_language,
                "digest_summary",
                returned=len(articles),
                total=resolved_total,
                limit=resolved_limit,
            ),
            "",
        ]
    )
    for article in articles:
        date = _escape_markdown(
            _output_text(article.get("published_at") or article.get("discovered_at") or "")[:10]
        )
        title = _escape_markdown(article["title"])
        url = _safe_http_url(article.get("canonical_url"))
        title_markup = "[%s](<%s>)" % (title, url) if url else title
        lines.append(
            "- %s — %s · %s"
            % (title_markup, _escape_markdown(article["source_name"]), date)
        )
        if article.get("summary"):
            lines.append("  %s" % _escape_markdown(article["summary"]))
    return "\n".join(lines) + "\n"


def render_feed(
    articles: Sequence[Dict[str, object]],
    *,
    language: str = "en",
) -> str:
    resolved_language = _normalize_language(language)
    rss = ET.Element("rss", {"version": "2.0"})
    channel = ET.SubElement(rss, "channel")
    ET.SubElement(channel, "title").text = "Aaron Reader"
    ET.SubElement(channel, "description").text = _TRANSLATIONS[resolved_language][
        "feed_description"
    ]
    ET.SubElement(channel, "language").text = resolved_language
    ET.SubElement(channel, "link").text = (
        "https://aaron-reader.aaron-he-zhu.workers.dev/"
    )
    ET.SubElement(channel, "lastBuildDate").text = datetime.now(timezone.utc).strftime(
        "%a, %d %b %Y %H:%M:%S +0000"
    )
    for article in articles:
        item = ET.SubElement(channel, "item")
        ET.SubElement(item, "title").text = _output_text(article["title"])
        safe_url = _safe_http_url(article.get("canonical_url"))
        if safe_url:
            ET.SubElement(item, "link").text = safe_url
        guid = safe_url or "urn:aaron-reader:%s" % quote(
            _output_text(article.get("id") or "unknown"), safe=""
        )
        ET.SubElement(item, "guid").text = guid
        ET.SubElement(item, "description").text = _output_text(article.get("summary") or "")
        ET.SubElement(item, "category").text = _output_text(article.get("source_name") or "")
        if article.get("published_at"):
            try:
                parsed = datetime.fromisoformat(
                    _output_text(article["published_at"]).replace("Z", "+00:00")
                )
                ET.SubElement(item, "pubDate").text = parsed.strftime("%a, %d %b %Y %H:%M:%S +0000")
            except ValueError:
                pass
    return '<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(
        rss, encoding="unicode", short_empty_elements=True
    ) + "\n"


def build_llm_packet(
    articles: Sequence[Dict[str, object]],
    max_chars: int = 6000,
    *,
    language: str = "en",
) -> Dict[str, object]:
    if not isinstance(max_chars, int) or isinstance(max_chars, bool) or max_chars <= 0:
        raise ValueError("max_chars must be a positive integer")
    resolved_language = _normalize_language(language)

    total_article_count = len(articles)
    selected: List[Dict[str, object]] = []
    truncated_summary_count = 0
    empty_packet = _finalize_packet(
        [],
        max_chars,
        total_article_count=total_article_count,
        truncated_summary_count=0,
        language=resolved_language,
    )
    if int(empty_packet["character_count"]) > max_chars:
        raise ValueError("max_chars is too small for packet metadata")

    for article in articles:
        item = _public_article(article)
        original_summary = str(item.get("summary") or "")
        summary = original_summary[:600]
        compact = {
            "id": item["id"],
            "source": item["source"],
            "published_at": item["published_at"],
            "title": item["title"],
            "summary": summary,
            "url": item["url"],
        }
        candidate_was_truncated = len(summary) < len(original_summary)
        trial = _finalize_packet(
            selected + [compact],
            max_chars,
            total_article_count=total_article_count,
            truncated_summary_count=truncated_summary_count + int(candidate_was_truncated),
            language=resolved_language,
        )
        if int(trial["character_count"]) > max_chars and summary:
            best_summary: Optional[str] = None
            lower = 0
            upper = len(summary)
            while lower <= upper:
                midpoint = (lower + upper) // 2
                candidate_summary = summary[:midpoint].rstrip()
                compact["summary"] = candidate_summary
                candidate_was_truncated = candidate_summary != original_summary
                trial = _finalize_packet(
                    selected + [compact],
                    max_chars,
                    total_article_count=total_article_count,
                    truncated_summary_count=(
                        truncated_summary_count + int(candidate_was_truncated)
                    ),
                    language=resolved_language,
                )
                if int(trial["character_count"]) <= max_chars:
                    best_summary = candidate_summary
                    lower = midpoint + 1
                else:
                    upper = midpoint - 1
            if best_summary is not None:
                compact["summary"] = best_summary
                candidate_was_truncated = best_summary != original_summary
                trial = _finalize_packet(
                    selected + [compact],
                    max_chars,
                    total_article_count=total_article_count,
                    truncated_summary_count=(
                        truncated_summary_count + int(candidate_was_truncated)
                    ),
                    language=resolved_language,
                )
        if int(trial["character_count"]) > max_chars:
            break
        selected.append(compact)
        truncated_summary_count += int(candidate_was_truncated)
    packet = _finalize_packet(
        selected,
        max_chars,
        total_article_count=total_article_count,
        truncated_summary_count=truncated_summary_count,
        language=resolved_language,
    )
    if int(packet["character_count"]) > max_chars:
        raise RuntimeError("final packet exceeds its character budget")
    return packet


def _finalize_packet(
    articles: Sequence[Dict[str, object]],
    max_chars: int,
    *,
    total_article_count: int,
    truncated_summary_count: int,
    language: str,
) -> Dict[str, object]:
    omitted_article_count = max(0, total_article_count - len(articles))
    packet: Dict[str, object] = {
        "language": language,
        "supported_languages": list(SUPPORTED_LANGUAGES),
        "instruction_hint": _TRANSLATIONS[language]["packet_instruction"],
        "input_article_count": total_article_count,
        "article_count": len(articles),
        "omitted_article_count": omitted_article_count,
        "truncated_summary_count": truncated_summary_count,
        "truncated": bool(omitted_article_count or truncated_summary_count),
        "character_budget": max_chars,
        "character_count": 0,
        "utf8_bytes": 0,
        "approx_tokens": 0,
        "articles": list(articles),
    }
    for _ in range(64):
        serialized = _pretty_packet_json(packet)
        character_count = len(serialized)
        utf8_bytes = len(serialized.encode("utf-8"))
        approx_tokens = (utf8_bytes + 3) // 4
        values = (
            int(packet["character_count"]),
            int(packet["utf8_bytes"]),
            int(packet["approx_tokens"]),
        )
        updated = (character_count, utf8_bytes, approx_tokens)
        packet["character_count"] = character_count
        packet["utf8_bytes"] = utf8_bytes
        packet["approx_tokens"] = approx_tokens
        if values == updated:
            break
    else:
        raise RuntimeError("packet size metadata did not converge")

    serialized = _pretty_packet_json(packet)
    if int(packet["character_count"]) != len(serialized):
        raise RuntimeError("packet character_count is not self-consistent")
    if int(packet["utf8_bytes"]) != len(serialized.encode("utf-8")):
        raise RuntimeError("packet utf8_bytes is not self-consistent")
    return packet


def _translation_ai_artifacts(value: object) -> List[Dict[str, object]]:
    """Expose only per-article translations while accepting legacy caches."""

    if not isinstance(value, list):
        return []
    return [
        item
        for item in value
        if isinstance(item, dict)
        and _output_text(item.get("task_type") or item.get("task"))
        == "translation"
    ]


def _public_article(article: Dict[str, object]) -> Dict[str, object]:
    result = {
        "id": article["id"],
        "source": _output_text(article["source_slug"]),
        "source_name": _output_text(article["source_name"]),
        "title": _output_text(article["title"]),
        "summary": _output_text(article.get("summary") or ""),
        "category": _output_text(article.get("category") or ""),
        "published_at": _output_text(article.get("published_at")) or None,
        "url": _safe_http_url(article.get("canonical_url")),
        "unread": not bool(article.get("read_at")),
        "starred": bool(article.get("starred_at")),
    }
    result["ai_artifacts"] = [
        _public_ai_artifact(item)
        for item in _translation_ai_artifacts(article.get("ai_artifacts"))
    ]
    return result


def _public_ai_artifact(artifact: Dict[str, object]) -> Dict[str, object]:
    try:
        output = json.loads(_output_text(artifact.get("output_json") or "{}"))
    except (TypeError, ValueError, json.JSONDecodeError):
        output = {}
    if not isinstance(output, dict):
        output = {}
    return {
        "id": int(artifact.get("id") or 0),
        "task": _output_text(
            artifact.get("task_type") or artifact.get("task") or ""
        ),
        "input_scope": _output_text(artifact.get("input_scope") or ""),
        "target_language": _output_text(artifact.get("target_language") or ""),
        "generated_at": _output_text(artifact.get("created_at") or "") or None,
        "input_truncated": bool(artifact.get("input_truncated")),
        "output": output,
    }


def _render_ai_artifacts(
    value: object, language: str
) -> tuple:
    if not isinstance(value, list):
        return "", ""
    translations = _TRANSLATIONS[language]
    markup: List[str] = []
    search_parts: List[str] = []
    for raw_artifact in _translation_ai_artifacts(value):
        artifact = _public_ai_artifact(raw_artifact)
        task = str(artifact["task"])
        scope = str(artifact["input_scope"])
        basis_key = "full_text_basis" if scope == "full_text" else "metadata_basis"
        label_key = "machine_translation"
        output = artifact["output"]
        if not isinstance(output, dict):
            output = {}
        body = ""
        translated_title = _output_text(output.get("title") or "")
        translated_summary = _output_text(output.get("publisher_summary") or "")
        search_parts.extend((translated_title, translated_summary))
        if translated_title:
            body += '<h3 class="translated-title">%s</h3>' % html.escape(
                translated_title
            )
        if translated_summary:
            body += '<p class="ai-output">%s</p>' % html.escape(
                translated_summary
            )
        if not body:
            continue
        generated = str(artifact.get("generated_at") or "")[:10]
        truncated = (
            ' · <span class="ai-warning" data-i18n="ai_truncated">%s</span>'
            % html.escape(translations["ai_truncated"])
            if artifact.get("input_truncated")
            else ""
        )
        markup.append(
            """
            <section class="ai-artifact" data-ai-task="%s" data-ai-language="%s">
              <div class="ai-label"><strong data-i18n="%s">%s</strong> · <span data-i18n="%s">%s</span> · <span>%s</span> · <time>%s</time>%s</div>
              %s
            </section>
            """
            % (
                html.escape(task, quote=True),
                html.escape(str(artifact["target_language"]), quote=True),
                label_key,
                html.escape(translations[label_key]),
                basis_key,
                html.escape(translations[basis_key]),
                html.escape(str(artifact["target_language"])),
                html.escape(generated),
                truncated,
                body,
            )
        )
    return "".join(markup), " ".join(search_parts)


def _pretty_packet_json(packet: Dict[str, object]) -> str:
    """Match the CLI's pretty JSON plus the newline emitted by ``print``."""

    return json.dumps(packet, ensure_ascii=False, indent=2) + "\n"


def _normalize_language(language: str) -> str:
    if not isinstance(language, str):
        raise ValueError("language must be 'en' or 'zh-CN'")
    normalized = language.strip().replace("_", "-").lower()
    if normalized == "en" or normalized.startswith("en-"):
        return "en"
    if normalized == "zh" or normalized.startswith("zh-"):
        return "zh-CN"
    raise ValueError("unsupported language %r; expected 'en' or 'zh-CN'" % language)


def _format_translation(language: str, key: str, **values: object) -> str:
    return _TRANSLATIONS[language][key].format(**values)


def _output_text(value: object) -> str:
    if value is None:
        return ""
    text = strip_control_characters(str(value))
    return re.sub(r"\s+", " ", text).strip()


def _safe_http_url(value: object) -> str:
    if value is None:
        return ""
    raw = str(value).strip()
    sanitized = strip_control_characters(raw, preserve_text_whitespace=False)
    if sanitized != raw:
        return ""
    try:
        parts = urlsplit(sanitized)
        if parts.scheme.lower() not in ("http", "https") or not parts.hostname:
            return ""
        if parts.username or parts.password:
            return ""
    except (TypeError, ValueError):
        return ""
    return quote(sanitized, safe=":/?#[]@!$&'()*+,;=%")


def _escape_markdown(value: object) -> str:
    text = _output_text(value)
    return _MARKDOWN_PUNCTUATION.sub(lambda match: "\\" + match.group(1), text)


def _source_health(source: Dict[str, object]) -> str:
    configured = _output_text(source.get("health")).lower()
    if configured in _HEALTH_CODES:
        return configured
    if source.get("last_error"):
        return "error"
    if not source.get("last_success_at"):
        return "never_synced"
    return "healthy"


def _resolve_counts(
    articles: Sequence[Dict[str, object]],
    statuses: Sequence[Dict[str, object]],
    counts: Optional[Dict[str, int]],
) -> Dict[str, int]:
    if counts is not None:
        return {
            "total": max(0, int(counts.get("total") or 0)),
            "unread": max(0, int(counts.get("unread") or 0)),
            "starred": max(0, int(counts.get("starred") or 0)),
        }
    has_aggregates = bool(statuses) and all("article_count" in source for source in statuses)
    total = (
        sum(int(source.get("article_count") or 0) for source in statuses)
        if has_aggregates
        else len(articles)
    )
    unread = (
        sum(int(source.get("unread_count") or 0) for source in statuses)
        if has_aggregates
        else sum(1 for article in articles if not article.get("read_at"))
    )
    return {
        "total": max(0, total),
        "unread": max(0, unread),
        "starred": sum(1 for article in articles if article.get("starred_at")),
    }


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=path.name + ".", dir=str(path.parent))
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise
