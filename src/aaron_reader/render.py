def render_outputs(
    database: Database,
    output_dir: Path,
    *,
    language: str = "en",
) -> None:
    resolved_language = _normalize_language(language)
    output_dir.mkdir(parents=True, exist_ok=True)
    recent_limit = max(PAGE_ARTICLE_LIMIT, LATEST_JSON_ARTICLE_LIMIT, FEED_ARTICLE_LIMIT)
    recent_articles = database.list_articles(limit=recent_limit)
    artifact_map = database.latest_ai_artifacts(
        [int(article["id"]) for article in recent_articles]
    )
    recent_articles = [
        dict(
            article,
            ai_artifacts=_translation_ai_artifacts(
                artifact_map.get(int(article["id"]), [])
            ),
        )
        for article in recent_articles
    ]
    page_articles = recent_articles[:PAGE_ARTICLE_LIMIT]
    latest_articles = recent_articles[:LATEST_JSON_ARTICLE_LIMIT]
    feed_articles = recent_articles[:FEED_ARTICLE_LIMIT]
    digest_articles = database.list_articles(
        limit=DIGEST_ARTICLE_LIMIT,
        unread_only=True,
    )
    statuses = database.source_statuses()
    counts = database.counts()
    _atomic_write(
        output_dir / "index.html",
        render_html(
            page_articles,
            statuses,
            counts=counts,
            article_limit=PAGE_ARTICLE_LIMIT,
            language=resolved_language,
        ),
    )
    _atomic_write(
        output_dir / "latest.json",
        render_json(
            latest_articles,
            statuses,
            counts=counts,
            article_limit=LATEST_JSON_ARTICLE_LIMIT,
            language=resolved_language,
        ),
    )
    _atomic_write(
        output_dir / "feed.xml",
        render_feed(feed_articles, language=resolved_language),
    )
    _atomic_write(
        output_dir / "digest.md",
        render_digest(
            digest_articles,
            total_count=counts["unread"],
            article_limit=DIGEST_ARTICLE_LIMIT,
            language=resolved_language,
        ),
    )


def render_index(
    database: Database,
    *,
    language: str = "en",
) -> str:
    """Render a fresh index without mutating any generated artifact."""

    resolved_language = _normalize_language(language)
    articles = database.list_articles(limit=PAGE_ARTICLE_LIMIT)
    artifact_map = database.latest_ai_artifacts(
        [int(article["id"]) for article in articles]
    )
    articles = [
        dict(
            article,
            ai_artifacts=_translation_ai_artifacts(
                artifact_map.get(int(article["id"]), [])
            ),
        )
        for article in articles
    ]
    return render_html(
        articles,
        database.source_statuses(),
        counts=database.counts(),
        article_limit=PAGE_ARTICLE_LIMIT,
        language=resolved_language,
    )


