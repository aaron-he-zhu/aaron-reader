def normalize_language(value: Optional[str], *, strict: bool = True) -> str:
    """Return a canonical locale name, accepting common aliases."""

    if value is None or not str(value).strip():
        return "en"
    normalized = str(value).strip().replace("_", "-").lower()
    language = _ALIASES.get(normalized)
    if language:
        return language
    if strict:
        raise ValueError(
            "unsupported language %r; supported languages: %s"
            % (value, ", ".join(SUPPORTED_LANGUAGES))
        )
    return "en"


def resolve_language(
    explicit: Optional[str] = None,
    config_default: Optional[str] = None,
    environ: Optional[Mapping[str, str]] = None,
) -> str:
    """Resolve explicit CLI > environment > config > English."""

    environment = os.environ if environ is None else environ
    for candidate in (explicit, environment.get("AARON_READER_LANG"), config_default, "en"):
        if candidate is not None and str(candidate).strip():
            return normalize_language(candidate)
    return "en"


def translate(key: str, language: str = "en", **values: object) -> str:
    """Translate a stable key with English fallback and safe formatting."""

    resolved = normalize_language(language)
    template = _MESSAGES.get(resolved, {}).get(key) or _MESSAGES["en"].get(key)
    if template is None:
        template = key
    try:
        return template.format(**values)
    except (KeyError, ValueError, IndexError) as exc:
        raise ValueError("invalid translation parameters for %s: %s" % (key, exc)) from exc
